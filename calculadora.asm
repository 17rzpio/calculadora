LIST P=16F690

#include <P16F690.INC>

__CONFIG
	_WDT_OFF &
    _PWRTE_ON &
    _MCLRE_OFF &
    _CP_OFF &
    _CPD_OFF

CBLOCK
	NUM1
	NUM2
	RESULTADO
	TEMP 
	CONTADOR

	ESTADO
	OPERACAO
	DISPLAY
	TEMP2
ENDC

ORG 0X0000
GOTO MAIN

ORG 0X0004
RETFIE

MAIN

CALL Inicializa

LOOP

CALL LerSelect
CALL LerEnter
CALL AtualizaDisplay

GOTO LOOP

Inicializa
	BANKSEL OSCCON
	MOVLW B'01100001'
	MOVWF OSCCON

	; TODOS DIGITAIS

	BANKSEL ANSEL
	CLRF ANSEL
	CLRF ANSELH

	; PORTA SAIDA

	BANKSEL TRISA
	CLRF TRISA

	; RC0 E RC1 ENTRADAS
	; RC2 RC3 RC4 SAIDAS

	MOVLW B'00000011'
	MOVWF TRISC

	; LIMPA PORTAS

	BANKSEL PORTA
	CLRF PORTA
	CLRF PORTC

	; ESTADO INICIAL

	CLRF NUM1
	CLRF NUM2
	CLRF RESULTADO
	CLRF TEMP 
	CLRF CONTADOR

	CLRF ESTADO
	CLRF OPERACAO
	CLRF DISPLAY
	CLRF TEMP2 
RETURN

LerSelect
RETURN

LerEnter
RETURN

AtualizaDisplay
RETURN

END