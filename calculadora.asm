LIST P=16F690

#include <P16F690.INC>

__CONFIG
	_WDT_OFF &
    _PWRTE_ON &
    _MCLRE_OFF &
    _CP_OFF &
    _CPD_OFF

CBLOCK
	NUM1
	NUM2
	RESULTADO
	TEMP 
	CONTADOR

	ESTADO
	OPERACAO
	DISPLAY
	TEMP2
	NUMERO_ENTRADA
	RAIZ
	QUADRADO
	AUX

	ANGULO
ENDC

ORG 0X0000
GOTO MAIN

ORG 0X0004
RETFIE

MAIN

CALL Inicializa

LOOP

CALL LerSelect
CALL LerEnter
CALL AtualizaDisplay

GOTO LOOP

Inicializa
	BANKSEL OSCCON
	MOVLW B'01100001'
	MOVWF OSCCON

	; TODOS DIGITAIS

	BANKSEL ANSEL
	CLRF ANSEL
	CLRF ANSELH

	; PORTA SAIDA

	BANKSEL TRISA
	CLRF TRISA

	; RC0 E RC1 ENTRADAS
	; RC2 RC3 RC4 SAIDAS

	MOVLW B'00000011'
	MOVWF TRISC

	; LIMPA PORTAS

	BANKSEL PORTA
	CLRF PORTA
	CLRF PORTC

	; ESTADO INICIAL

	CLRF NUM1
	CLRF NUM2
	CLRF RESULTADO
	CLRF TEMP 
	CLRF CONTADOR

	CLRF ESTADO
	CLRF OPERACAO
	CLRF DISPLAY
	CLRF TEMP2 

	MOVLW .3
	MOVWF ANGULO

	CALL CALCULA_SENO
RETURN

LerSelect
RETURN

LerEnter
RETURN

AtualizaDisplay
RETURN

Divisao
	CLRF RESULTADO
DivLoop
	MOVF NUM2,W
	SUBWF NUM1,F
	BTFSS STATUS,C
	GOTO DivFim
	INCF RESULTADO,F
	GOTO DivLoop
DivFim
	MOVF RESULTADO,W
	MOVWF DISPLAY
	RETURN

Multiplicacao
	CLRF RESULTADO
	MOVF NUM2,W
	MOVWF TEMP
MultLoop
	MOVF TEMP,F
	BTFSC STATUS,Z
	GOTO MultFim
	MOVF NUM1,W
	ADDWF RESULTADO,F
	DECF TEMP,F
	GOTO MultLoop
MultFim
	MOVF RESULTADO,W
	MOVF DISPLAY
	RETURN

RaizQuadrada
	CLRF RESULTADO
	CLRF TEMP 
RaizLoop
	INCF RESULTADO,F 

	;TEMP = RESULTADO X RESULTADO 
	MOVF RESULTADO,W 
	MOVWF NUM2  

	MOVF RESULTADO,W 
	MOVWF NUM1

	CALL Multiplicacao 

	MOVF RESULTADO,W 
	SUBWF NUMERO_ENTRADA,W

	BTFSC STATUS,c
	GOTO RaizLoop 

	DECF RESULTADO,F

	RETURN   

CALCULA_SENO:
	MOVF ANGULO,W 
	CALL TABELA_SENO 
	MOVWF RESULTADO
	RETURN

TABELA_SENO:
	ADDWF PCL,F 
	RETLW .0
	RETLW .2
	RETLW .3
	RETLW .5
	RETLW .6
	RETLW .7
	RETLW .8
	RETLW .8
	RETLW .9
	RETLW .9

END